/**
 * Промпт для глубокого визуального анализа портфолио дизайнера.
 *
 * Вход: текст со страниц портфолио + скриншоты кейсов (Gemini Vision).
 * Выход: JSON с 7 числовыми оценками + объяснения, разбор кейсов,
 *        red flags, общая оценка.
 *
 * Оценки сохраняются в полях Candidate.{visualStrength, uxStrength, ...}
 * и используются движком матчинга.
 */
export function buildPortfolioAnalyzePrompt(
  scrapedText: string,
  context?: { name?: string; role?: string; grade?: string },
): string {
  const ctx = context
    ? `Контекст: кандидат — ${context.name ?? "?"}, заявленная роль — ${
        context.role ?? "?"
      }, грейд — ${context.grade ?? "?"}.\n`
    : "";

  return `Ты — опытный design-lead, который оценивает портфолио дизайнеров для рекрутинга в студию Pragmatica (специализируется на найме продуктовых дизайнеров). Твоя задача — внимательно изучить скриншоты кейсов и текст портфолио, и дать честную, не завышенную оценку.

КРИТИЧЕСКИ ВАЖНО: ВСЕ текстовые поля в ответе пиши ТОЛЬКО НА РУССКОМ ЯЗЫКЕ. Это касается scoreExplanations, описаний кейсов, strengths, concerns, redFlags, overallAssessment — абсолютно всех текстов. Даже если портфолио на английском — твой ответ на русском. Не используй английские слова, кроме общепринятых терминов (UX, UI, A/B-тест, JTBD и т.п.).

${ctx}
ВХОДНЫЕ ДАННЫЕ:
- Скриншоты (страницы портфолио и кейсы) — изучи их визуально
- Текстовое содержимое страниц портфолио (см. ниже)

ЧТО ОЦЕНИВАТЬ (каждая шкала 0-100):

1. **visualStrength** — визуальное качество: типографика, композиция, выравнивание, цвет, контраст, плотность информации, внимание к деталям. Смотри на скриншоты в первую очередь.

2. **uxStrength** — UX-зрелость: понятность интерфейсов, продуманность флоу, корректное использование паттернов, информационная архитектура, состояния (loading/empty/error), доступность.

3. **productMaturity** — продуктовое мышление: понимает ли кандидат бизнес-задачу, объясняет ли ПОЧЕМУ принимал решения (а не только ЧТО сделал), думает ли о пользователях и метриках.

4. **systemThinking** — системность: дизайн-системы, переиспользуемые компоненты, масштабируемость решений, последовательность стилей между кейсами.

5. **argumentationQuality** — качество аргументации: есть ли гипотезы, рассуждения, альтернативы, обоснования. Кейс — это рассказ или просто галерея экранов?

6. **metricsImpact** — измеримое влияние: указаны ли реальные метрики (конверсия, retention, NPS, экономия времени), масштаб (DAU, выручка), результаты A/B-тестов.

7. **researchDepth** — глубина исследования: пользовательские интервью, юзабилити-тесты, аналитика, конкурентный анализ, JTBD, персоны. Если кандидат UX-researcher — это критично.

ВАЖНЫЕ ПРИНЦИПЫ ОЦЕНКИ:
- Не завышай оценки. 80+ — это уровень senior+. 60-70 — крепкий middle. 40-55 — junior с потенциалом. <40 — слабо/нерелевантно для нашей цели.
- Если данных мало (например, в кейсе только финальные экраны без процесса) — это понижает researchDepth и argumentationQuality.
- Если все кейсы выглядят как полированные мокапы без объяснений — это red flag для productMaturity.
- Если кейсы похожи на популярные шаблоны из Dribbble — это red flag.

ОТДЕЛЬНО ОПИШИ КАЖДЫЙ КЕЙС:
- Название
- Краткое описание (1-2 предложения)
- 2-4 сильные стороны (что хорошо)
- 1-3 слабых сторон / вопросов (что вызывает сомнения или что хотелось бы доуточнить)

RED FLAGS — отметь, если видишь:
- Только финальные мокапы, нет процесса
- Шаблонные решения, скопированные с популярных портфолио
- Несоответствие заявленной роли (например, графический дизайн при заявке на product)
- Сильные расхождения в качестве между кейсами (намёк на чужую работу)
- Несвежие работы (UI 2018-2020 года)

ФОРМАТ ОТВЕТА — СТРОГО JSON, БЕЗ MARKDOWN, БЕЗ КОММЕНТАРИЕВ:

{
  "scores": {
    "visualStrength": <0-100>,
    "uxStrength": <0-100>,
    "productMaturity": <0-100>,
    "systemThinking": <0-100>,
    "argumentationQuality": <0-100>,
    "metricsImpact": <0-100>,
    "researchDepth": <0-100>
  },
  "scoreExplanations": {
    "visualStrength": "<1-2 предложения почему такая оценка>",
    "uxStrength": "<1-2 предложения>",
    "productMaturity": "<1-2 предложения>",
    "systemThinking": "<1-2 предложения>",
    "argumentationQuality": "<1-2 предложения>",
    "metricsImpact": "<1-2 предложения>",
    "researchDepth": "<1-2 предложения>"
  },
  "cases": [
    {
      "title": "<название кейса>",
      "description": "<1-2 предложения о чём кейс>",
      "strengths": ["<сильная сторона>", ...],
      "concerns": ["<слабая сторона или вопрос>", ...]
    }
  ],
  "overallAssessment": "<2-4 предложения: общее впечатление, насколько кандидат соответствует заявленной роли/грейду, есть ли потенциал>",
  "redFlags": ["<red flag>", ...],
  "strengths": ["<главная сильная сторона>", "<...>", "<...>"],
  "concerns": ["<главное опасение>", "<...>", "<...>"]
}

Если кейсов нет / портфолио пустое — верни все оценки = null и redFlags = ["Портфолио пустое или недоступно"].

ТЕКСТ ПОРТФОЛИО:
${scrapedText.slice(0, 25000)}
`;
}
