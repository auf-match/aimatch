import { staleBefore, todayBlock } from "@/lib/prompt-date";

/**
 * Промпт для глубокого визуального анализа портфолио дизайнера.
 *
 * Вход: текст со страниц портфолио + скриншоты кейсов (Gemini Vision).
 * Выход: JSON с 7 числовыми оценками + объяснения, разбор кейсов,
 *        red flags, общая оценка.
 *
 * Оценки сохраняются в полях Candidate.{visualStrength, uxStrength, ...}
 * и используются движком матчинга.
 */
export function buildPortfolioAnalyzePrompt(
  scrapedText: string,
  context?: { name?: string; role?: string; grade?: string },
  today: Date = new Date(),
): string {
  const ctx = context
    ? `Контекст: кандидат — ${context.name ?? "?"}, заявленная роль — ${
        context.role ?? "?"
      }, грейд — ${context.grade ?? "?"}.\n`
    : "";

  return `${todayBlock(today)}

Ты — опытный design-lead, который оценивает портфолио дизайнеров для рекрутинга в студию Pragmatica (специализируется на найме продуктовых дизайнеров). Твоя задача — внимательно изучить скриншоты кейсов и текст портфолио, и дать честную, не завышенную оценку.

ВИЗУАЛ ЗДЕСЬ НЕ ОЦЕНИВАЕТСЯ. Качество визуального дизайна считается отдельно, по одним скриншотам, без этого текста. Не выставляй визуальных оценок и не рассуждай о качестве картинки — сосредоточься на продуктовом мышлении, процессе и результатах.

КРИТИЧЕСКИ ВАЖНО: ВСЕ текстовые поля в ответе пиши ТОЛЬКО НА РУССКОМ ЯЗЫКЕ. Это касается scoreExplanations, описаний кейсов, strengths, concerns, redFlags, overallAssessment — абсолютно всех текстов. Даже если портфолио на английском — твой ответ на русском. Не используй английские слова, кроме общепринятых терминов (UX, UI, A/B-тест, JTBD и т.п.).

${ctx}
ВХОДНЫЕ ДАННЫЕ:
- Скриншоты (страницы портфолио и кейсы) — изучи их визуально
- Текстовое содержимое страниц портфолио (см. ниже)

ЧТО ОЦЕНИВАТЬ (каждая шкала 0-100):

1. **uxStrength** — UX-зрелость: понятность интерфейсов, продуманность флоу, корректное использование паттернов, информационная архитектура, состояния (loading/empty/error), доступность.

2. **productMaturity** — продуктовое мышление: понимает ли кандидат бизнес-задачу, объясняет ли ПОЧЕМУ принимал решения (а не только ЧТО сделал), думает ли о пользователях и метриках.

3. **systemThinking** — системность: дизайн-системы, переиспользуемые компоненты, масштабируемость решений, последовательность стилей между кейсами.

4. **argumentationQuality** — качество аргументации: есть ли гипотезы, рассуждения, альтернативы, обоснования. Кейс — это рассказ или просто галерея экранов?

5. **metricsImpact** — измеримое влияние: указаны ли реальные метрики (конверсия, retention, NPS, экономия времени), масштаб (DAU, выручка), результаты A/B-тестов.

6. **researchDepth** — глубина исследования: пользовательские интервью, юзабилити-тесты, аналитика, конкурентный анализ, JTBD, персоны. Если кандидат UX-researcher — это критично.

ВАЖНЫЕ ПРИНЦИПЫ ОЦЕНКИ:
- Не завышай оценки. 80+ — это уровень senior+. 60-70 — крепкий middle. 40-55 — junior с потенциалом. <40 — слабо/нерелевантно для нашей цели.

- **ИСПОЛЬЗУЙ ВЕСЬ ДИАПАЗОН.** Не жмись к середине. Если работа посредственная — ставь 55, а не 70. Если выдающаяся — ставь 92, а не 80. Оценка 70-75 должна быть осознанным выводом, а не значением по умолчанию. Одинаковые оценки по всем шкалам — почти всегда признак того, что ты не разобрался: шкалы независимы, сильный визуал часто соседствует со слабыми метриками и наоборот.

- **ОЖИДАЕМОЕ РАСПРЕДЕЛЕНИЕ.** В типичной выборке дизайнеров: около 10% попадают в 80+, около 30% в 65-79, около 40% в 50-64, около 20% ниже 50. Твоя оценка должна укладываться в эту картину мира.

- **ОТДЕЛЯЙ КАЧЕСТВО ИСПОЛНЕНИЯ ОТ СЛОЖНОСТИ ЗАДАЧИ.** Красивый промо-лендинг решает несопоставимо более простую визуальную задачу, чем плотный интерфейс с десятками состояний. Не ставь высокий visualStrength только за то, что работа приятно выглядит на простой задаче.

- Не снижай оценку за качество самого скриншота (сжатие, обрезка, длинная прокрутка) — оценивай саму работу.

- Если данных мало (например, в кейсе только финальные экраны без процесса) — это понижает researchDepth и argumentationQuality.
- Если все кейсы выглядят как полированные мокапы без объяснений — это red flag для productMaturity.
- Если кейсы похожи на популярные шаблоны из Dribbble — это red flag.

ОТДЕЛЬНО ОПИШИ КАЖДЫЙ КЕЙС:
- Название
- Краткое описание (1-2 предложения)
- 2-4 сильные стороны (что хорошо)
- 1-3 слабых сторон / вопросов (что вызывает сомнения или что хотелось бы доуточнить)

RED FLAGS — отметь, если видишь:
- Только финальные мокапы, нет процесса
- Шаблонные решения, скопированные с популярных портфолио
- Несоответствие заявленной роли (например, графический дизайн при заявке на product)
- Сильные расхождения в качестве между кейсами (намёк на чужую работу)
- Несвежие работы: последний кейс старше ${staleBefore(today)} года

ФОРМАТ ОТВЕТА — СТРОГО JSON, БЕЗ MARKDOWN, БЕЗ КОММЕНТАРИЕВ:

{
  "scores": {
    "uxStrength": <0-100>,
    "productMaturity": <0-100>,
    "systemThinking": <0-100>,
    "argumentationQuality": <0-100>,
    "metricsImpact": <0-100>,
    "researchDepth": <0-100>
  },
  "scoreExplanations": {
    "uxStrength": "<1-2 предложения>",
    "productMaturity": "<1-2 предложения>",
    "systemThinking": "<1-2 предложения>",
    "argumentationQuality": "<1-2 предложения>",
    "metricsImpact": "<1-2 предложения>",
    "researchDepth": "<1-2 предложения>"
  },
  "cases": [
    {
      "title": "<название кейса>",
      "description": "<1-2 предложения о чём кейс>",
      "strengths": ["<сильная сторона>", ...],
      "concerns": ["<слабая сторона или вопрос>", ...]
    }
  ],
  "overallAssessment": "<2-4 предложения: общее впечатление, насколько кандидат соответствует заявленной роли/грейду, есть ли потенциал>",
  "redFlags": ["<red flag>", ...],
  "strengths": ["<главная сильная сторона>", "<...>", "<...>"],
  "concerns": ["<главное опасение>", "<...>", "<...>"]
}

Если кейсов нет / портфолио пустое — верни все оценки = null и redFlags = ["Портфолио пустое или недоступно"].

ТЕКСТ ПОРТФОЛИО:
${scrapedText.slice(0, 25000)}
`;
}
