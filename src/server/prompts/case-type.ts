/**
 * Разметка кейсов по типу продукта — отдельным запросом, до оценки визуала.
 *
 * Раньше это решение принимала сама оценивающая модель по ходу дела, и на
 * смешанном портфолио набор кейсов плавал: три прогона подряд дали 74 по
 * личному кабинету, 78 по фитнесу и 68 снова по фитнесу. Разброс в десять
 * баллов при том, что вход не менялся.
 *
 * Теперь тип определяется один раз, ответ сохраняется, и на оценку визуала
 * уходит фиксированный набор кадров.
 *
 * Запрос дешёвый: по одному кадру на кейс плюс заголовок, ответ — список.
 */
export function buildCaseTypePrompt(
  cases: { index: number; title: string }[],
): string {
  const список = cases
    .map((c) => `${c.index}. ${c.title || "без заголовка"}`)
    .join("\n");

  return `Определи тип продукта в каждом кейсе портфолио дизайнера. Ничего не оценивай — только классифицируй.

КЕЙСЫ (номер и заголовок):
${список}

К каждому кейсу приложен один кадр с пометкой «[кейс N]».

ТИПЫ:

**b2c** — продукт для обычных людей: мобильные приложения, маркетплейсы, доставка, финансы для частных лиц, медиа, обучение, здоровье, путешествия, соцсети, личные кабинеты клиентов, сайты услуг.

**b2b** — рабочий инструмент для сотрудников или компаний: дашборды, админки, back-office, CRM, ERP, аналитические и промышленные системы, внутренние панели, инструменты для операторов и специалистов.

КАК РЕШАТЬ В СПОРНЫХ СЛУЧАЯХ:
• Личный кабинет клиента — это b2c, даже если продукт корпоративный: им пользуется обычный человек.
• Инструмент для сотрудников заказчика — b2b, даже если выглядит нарядно.
• Смотри, КТО пользуется каждый день, а не кто платит.
• Если по кадру и заголовку понять невозможно — ставь b2c: потребительских продуктов в портфолио дизайнеров большинство, и ошибка в эту сторону дешевле.

ОТВЕТ — СТРОГО JSON, без markdown:

{"кейсы": [{"номер": 1, "тип": "b2c"}, {"номер": 2, "тип": "b2b"}]}

Верни ровно столько записей, сколько кейсов в списке.`;
}
