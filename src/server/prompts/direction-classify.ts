/**
 * Промпт классификации направления дизайнера:
 * продуктовый (product) или коммуникационный (communication).
 *
 * Применяется для неоднозначных ролей: ART_DIRECTOR, DESIGN_LEAD, OTHER.
 * По результату выбирается нужный рубрик оценки портфолио.
 */
export function buildDirectionClassifyPrompt(
  scrapedText: string,
  context?: { role?: string; grade?: string },
): string {
  const ctx = context
    ? `Заявленная роль: ${context.role ?? "не указана"}, грейд: ${context.grade ?? "не указан"}.\n`
    : "";

  return `Ты — опытный рекрутер дизайнеров. Тебе нужно определить, в каком направлении работает дизайнер: продуктовый дизайн или коммуникационный/брендинговый дизайн.

${ctx}
ПРОДУКТОВЫЙ ДИЗАЙН — признаки:
- Проектирование интерфейсов приложений, сайтов, сервисов
- UX/UI, пользовательские флоу, информационная архитектура
- Дизайн-системы для цифровых продуктов (Figma components, tokens)
- A/B-тесты, метрики конверсии, retention
- Кейсы с задачами типа "улучшить онбординг", "редизайн корзины", "новый дашборд"
- Работа с продуктовыми командами (PM, разработчики)

КОММУНИКАЦИОННЫЙ ДИЗАЙН — признаки:
- Брендинг и айдентика: логотипы, фирменный стиль, гайдлайны
- Полиграфия: постеры, упаковка, буклеты, баннеры
- Иллюстрация и типографика как самостоятельное направление
- Рекламные материалы: наружная реклама, SMM-графика
- Моушн-графика, анимация, видеодизайн
- Кейсы с задачами типа "создать айдентику бренда", "разработать рекламную кампанию"

СМЕШАННЫЙ СЛУЧАЙ:
- Дизайн-лиды и арт-директоры могут вести оба направления — смотри на ПРЕОБЛАДАЮЩИЙ тип работ
- Если в портфолио 70%+ одного типа — это и есть направление
- Если 50/50 — выбери то, что явно более сильное/качественное в портфолио

КРИТИЧЕСКИ ВАЖНО: ВСЕ текстовые поля пиши ТОЛЬКО НА РУССКОМ ЯЗЫКЕ.

ФОРМАТ ОТВЕТА — СТРОГО JSON, БЕЗ MARKDOWN:

{
  "direction": "product" | "communication",
  "confidence": <0-100, насколько уверен>,
  "reasoning": "<2-3 предложения объяснения: что именно в портфолио указывает на это направление>"
}

Примеры confidence:
- 90-100: явный продуктовый или коммуникационный, сомнений нет
- 70-89: преобладает одно направление, но есть элементы другого
- 50-69: примерно 50/50, выбрал по преобладанию, но уверенности нет
- <50: почти невозможно определить, данных мало или очень смешанное

ТЕКСТ ПОРТФОЛИО:
${scrapedText.slice(0, 20000)}
`;
}
