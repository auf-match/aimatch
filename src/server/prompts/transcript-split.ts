/**
 * Промпт разметки одного звонка по нескольким вакансиям.
 *
 * Вход: пронумерованный транскрипт + список вакансий, которые обсуждались.
 * Выход: диапазоны строк на каждую вакансию. Текст модель НЕ переписывает —
 * нарезка делается кодом (см. src/lib/transcript-split.ts).
 */

export interface SplitVacancyInfo {
  id: string;
  title: string;
  clientName?: string | null;
  role?: string | null;
  grade?: string | null;
}

export function buildTranscriptSplitPrompt(args: {
  numberedTranscript: string;
  vacancies: SplitVacancyInfo[];
}): string {
  const list = args.vacancies
    .map(
      (v, i) =>
        `${i + 1}. id: "${v.id}"\n   Название: ${v.title}\n   Клиент: ${
          v.clientName ?? "не указан"
        }\n   Роль/грейд: ${v.role ?? "?"} / ${v.grade ?? "?"}`,
    )
    .join("\n");

  return `Ты разбираешь запись рабочего звонка рекрутингового агентства. На одном звонке обсуждали НЕСКОЛЬКО вакансий — обычно последовательно: сначала одну, потом другую.

Твоя задача — определить, какие строки транскрипта относятся к какой вакансии.

ВАКАНСИИ, КОТОРЫЕ ОБСУЖДАЛИСЬ:
${list}

ПРАВИЛА:
1. Опирайся на содержание: названия компаний и продуктов, роль и грейд, задачи, имена участников команды, суммы вилок. Переход к следующей вакансии почти всегда обозначен явно («так, теперь по второй позиции», «а что по дизайнеру для X»).
2. Разговор может ВЕРНУТЬСЯ к ранее обсуждённой вакансии в конце звонка. В этом случае верни для неё НЕСКОЛЬКО диапазонов — это нормально.
3. Общие части (приветствия, обсуждение сроков оплаты, болтовня, прощание) НЕ относи ни к одной вакансии — просто не включай эти строки ни в один диапазон. Лучше потерять нейтральную реплику, чем приписать условие не той вакансии.
4. Если фрагмент явно относится к вакансии, которой НЕТ в списке выше — не включай его никуда.
5. Не переписывай и не пересказывай текст. Возвращай ТОЛЬКО номера строк.
6. Границы диапазонов — по смыслу, а не по ровным числам. Захватывай реплику целиком.

ТРАНСКРИПТ (в формате «номер| текст»):
${args.numberedTranscript}

ФОРМАТ ОТВЕТА — СТРОГО JSON, БЕЗ MARKDOWN, БЕЗ КОММЕНТАРИЕВ:

{
  "ranges": [
    { "vacancyId": "<id из списка выше>", "fromLine": <число>, "toLine": <число>, "why": "<коротко: по каким признакам опознал>" }
  ]
}

Поле vacancyId — точное значение id из списка, не название вакансии.
Если разделить запись невозможно (звонок не про эти вакансии, или невозможно понять границы) — верни {"ranges": []}.
`;
}
