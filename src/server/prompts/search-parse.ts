/**
 * Промпт разбора поискового запроса «найди как».
 *
 * Вход: свободный текст рекрутера (напр. «сеньор с энтерпрайзом и финтехом,
 *       желательно из bigtech»).
 * Выход: JSON с жёсткими фильтрами (роль, грейд, локация, bigtech) + чистый
 *        семантический текст для векторного ранжирования.
 *
 * Ключевой принцип: жёсткие, однозначные ограничения → фильтры (SQL);
 * мягкие предпочтения («желательно», «плюсом») → в semanticQuery
 * (влияют на ранжирование, но не отсекают).
 */
export function buildSearchParsePrompt(query: string): string {
  return `Ты — ассистент рекрутингового агентства дизайнеров. Тебе дан поисковый запрос на естественном языке. Разбери его на структурированные фильтры и семантическую часть.

ДОСТУПНЫЕ РОЛИ (enum):
PRODUCT_DESIGNER, UX_DESIGNER, UI_DESIGNER, COMMUNICATION_DESIGNER, UX_RESEARCHER, DESIGN_LEAD, ART_DIRECTOR, BRAND_DESIGNER, MOTION_DESIGNER, OTHER

ДОСТУПНЫЕ ГРЕЙДЫ (по возрастанию):
JUNIOR, MIDDLE, MIDDLE_PLUS, SENIOR, SENIOR_PLUS, LEAD, HEAD

ПРАВИЛА РАЗБОРА:
1. roles — массив ролей, если в запросе явно названа роль/специальность. Иначе null.
2. grades — массив подходящих грейдов. «сеньор» → ["SENIOR","SENIOR_PLUS","LEAD","HEAD"] (сеньор и выше). «миддл» → ["MIDDLE","MIDDLE_PLUS"]. «джун» → ["JUNIOR"]. «лид» → ["LEAD","HEAD"]. Если грейд не указан — null.
3. location — город/страна, ТОЛЬКО если это жёсткое требование (напр. «в Москве», «офис в Берлине»). Иначе null.
4. hasBigtech — true ТОЛЬКО если bigtech-опыт назван ОБЯЗАТЕЛЬНЫМ («обязательно из bigtech», «только из крупных корпораций»). Если сказано «желательно», «плюсом», «хорошо бы» — НЕ ставь true, вместо этого отрази это в semanticQuery. Иначе null.
5. semanticQuery — чистая семантическая суть запроса для векторного поиска: домены, индустрии, типы продуктов, навыки, мягкие предпочтения. Пиши кратко и по делу, можно на русском. НЕ дублируй сюда жёсткие грейды/локацию (они уже в фильтрах), но мягкие предпочтения по опыту — включай.
6. interpretation — короткая человекочитаемая фраза (на русском), что ты понял из запроса. Для показа рекрутеру.

КРИТИЧЕСКИ ВАЖНО: верни СТРОГО JSON, без markdown, без комментариев.

ПРИМЕР:
Запрос: «сеньор продуктовый с энтерпрайзом и финтехом, желательно из bigtech»
Ответ:
{
  "roles": ["PRODUCT_DESIGNER"],
  "grades": ["SENIOR","SENIOR_PLUS","LEAD","HEAD"],
  "location": null,
  "hasBigtech": null,
  "semanticQuery": "enterprise UX, B2B, финтех, банковские и платёжные продукты, желателен опыт в bigtech",
  "interpretation": "Сеньор+ продуктовый дизайнер с опытом в enterprise и финтехе, плюсом — bigtech"
}

ФОРМАТ ОТВЕТА:
{
  "roles": <string[] | null>,
  "grades": <string[] | null>,
  "location": <string | null>,
  "hasBigtech": <true | null>,
  "semanticQuery": "<строка>",
  "interpretation": "<строка>"
}

ЗАПРОС ДЛЯ РАЗБОРА:
${query.slice(0, 1000)}
`;
}
