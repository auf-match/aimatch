/**
 * Промпт для буквальной транскрипции записи Zoom-брифинга.
 * Цель — получить чистый текст со спикерами, без пересказа и сокращений.
 */
export function buildBriefingTranscribePrompt(): string {
  return `Тебе подан аудиофайл — запись встречи (брифинг по найму дизайнера).

Расшифруй аудио ДОСЛОВНО. Не пересказывай. Не сокращай. Не суммируй.

ПРАВИЛА:
1. Сохраняй язык оригинала (обычно русский). Не переводи.
2. Размечай говорящих метками "[Спикер 1]", "[Спикер 2]" и т.д. Если кто-то называет имя — добавь его в скобках, например "[Спикер 1, Анна]".
3. Каждая реплика на новой строке, начинается с метки спикера.
4. Сохраняй мелочи: "ээ", "ну", повторы — НЕ убирай. Это важно для контекста.
5. Если что-то неразборчиво — пиши "[неразборчиво]".
6. Не добавляй своих комментариев, оценок, никаких вводных фраз. ТОЛЬКО транскрипт.
7. НЕ оборачивай ответ в markdown / code blocks.

Пример формата:
[Спикер 1, Анна] Привет, мы ищем продуктового дизайнера на проект.
[Спикер 2] Какой грейд?
[Спикер 1, Анна] Миддл+ или сеньор, в зависимости от уровня.

Начинай транскрипт прямо с первой реплики.`;
}
