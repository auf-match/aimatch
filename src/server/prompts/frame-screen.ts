/**
 * Отбор кадров, на которых действительно есть интерфейс.
 *
 * Зачем: страницы кейсов на портфолио-площадках — это развороты о продукте,
 * а не продукт. Чёрный экран с крупным заголовком и таблицей мета-данных,
 * обложка кейса, цитата на весь экран, фотография команды. Оценить такой
 * кадр плохо невозможно — там нечему сбиться, и модель ставила 92 портфолио,
 * визуал которого дизайн-лид считает слабым.
 *
 * Замер, ради которого это написано: у одного портфолио три прогона дали
 * 70, 88 и 92. Разброс в 22 балла объяснялся тем, попали ли в выборку
 * настоящие экраны или одни развороты.
 *
 * Отбор дешёвый: ответ — список номеров, рассуждений не требуется.
 */
export function buildFrameScreenPrompt(total: number): string {
  return `Перед тобой ${total} кадров со страниц портфолио дизайнера. Каждый кадр помечен номером: [кадр 1], [кадр 2] и так далее.

Твоя задача — механическая: определить, на каких кадрах ВИДЕН ЭКРАН ЦИФРОВОГО ПРОДУКТА. Ничего не оценивай, качество не обсуждай.

СЧИТАЕТСЯ ИНТЕРФЕЙСОМ:
• экран приложения или сайта — целиком или крупным фрагментом;
• экран в рамке телефона или ноутбука (мокап) — если сам экран различим;
• несколько экранов рядом, показывающих поток или сравнение «до и после»;
• фрагмент интерфейса: форма, список, карточка товара, таблица, панель настроек, состояние загрузки или ошибки;
• компоненты дизайн-системы: кнопки, поля, элементы навигации.

НЕ СЧИТАЕТСЯ ИНТЕРФЕЙСОМ:
• обложка кейса, заголовок на весь экран, крупная надпись поверх фото;
• таблица мета-данных о проекте: роль, платформы, инструменты, аудитория;
• абзацы текста, цитаты, описание задачи без картинок;
• схемы, карты пути, диаграммы, блок-схемы;
• фотографии людей, предметов, офиса;
• логотипы, цветовые палитры, образцы шрифтов сами по себе;
• интерфейс САМОЙ площадки — навигация Behance, боковые панели, футеры, плашки «Made in Framer»;
• кадр, состоящий в основном из пустого места.

Если на кадре есть и заголовок, и настоящий экран продукта — засчитывай как интерфейс. Если экран в мокапе такой мелкий, что деталей не разобрать, — не засчитывай.

ОТВЕТ — СТРОГО JSON, без markdown и пояснений:

{"интерфейс": [номера кадров, где виден экран продукта]}

Если подходящих кадров нет вовсе, верни {"интерфейс": []}.`;
}
