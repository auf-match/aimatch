/**
 * Промпт определения: сколько вакансий обсуждали на одном брифинге и где границы.
 *
 * Отличие от transcript-split: там список вакансий известен заранее, здесь
 * их ещё не существует — модель сама выделяет позиции и даёт им названия.
 * Текст не переписывается, возвращаются только номера строк.
 */
export function buildBriefingDetectPrompt(numberedTranscript: string): string {
  return `Ты разбираешь запись брифинга рекрутингового агентства по найму дизайнеров. На одном звонке могли обсуждать ОДНУ позицию, а могли НЕСКОЛЬКО — обычно последовательно: сначала одну, потом другую.

Твоя задача — определить, сколько РАЗНЫХ позиций обсуждали и какие строки к какой относятся.

ПРАВИЛА:
1. Разные позиции — это разные роли, разные грейды или разные продукты/команды. Признаки перехода: «так, теперь по второй позиции», «а ещё нам нужен…», смена названия продукта или клиента.
2. НЕ дроби одну позицию на части. Обсуждение задач, вилки, команды и процесса найма по одной и той же роли — это ОДНА позиция, даже если разговор к ней возвращался. Если сомневаешься, одна это позиция или две, считай, что одна.
3. Разговор может ВЕРНУТЬСЯ к ранее обсуждённой позиции. Тогда верни для неё несколько диапазонов с ОДИНАКОВЫМ label — они склеятся.
4. Общие части (приветствия, оплата услуг агентства, болтовня, прощание) не относи никуда — не включай эти строки ни в один диапазон.
5. label — короткое понятное название позиции, по которому человек её узнает: роль + компания или продукт. Например «Senior Product Designer, Х5» или «Арт-директор, Ростикс». Если компания не названа — только роль.
6. Не переписывай текст. Возвращай только номера строк.

ТРАНСКРИПТ (в формате «номер| текст»):
${numberedTranscript}

ФОРМАТ ОТВЕТА — СТРОГО JSON, БЕЗ MARKDOWN, БЕЗ КОММЕНТАРИЕВ:

{
  "segments": [
    { "label": "<короткое название позиции>", "fromLine": <число>, "toLine": <число> }
  ]
}

Если на записи обсуждали одну позицию — верни ОДИН сегмент на весь смысловой объём разговора.
`;
}
