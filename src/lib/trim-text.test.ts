import { describe, it, expect } from "vitest";
import { обрезатьПоСловам } from "./trim-text";

describe("обрезатьПоСловам", () => {
  it("короткий текст не трогает", () => {
    expect(обрезатьПоСловам("Композиция уверенная.", 100)).toBe("Композиция уверенная.");
  });

  it("режет по границе слова, а не посреди него", () => {
    const r = обрезатьПоСловам("Композиция и типографика на уверенном уровне", 20);
    expect(r).toBe("Композиция и…");
    expect(r).not.toMatch(/типограф[^и]/);
  });

  it("укладывается в предел вместе с многоточием", () => {
    for (const предел of [10, 20, 40, 80]) {
      const r = обрезатьПоСловам("Композиция и типографика на уверенном уровне экрана", предел);
      expect(r.length, `предел ${предел}`).toBeLessThanOrEqual(предел);
    }
  });

  it("не оставляет знаки препинания перед многоточием", () => {
    expect(обрезатьПоСловам("Флоу читаются, паттерны на месте", 16)).toBe("Флоу читаются…");
    expect(обрезатьПоСловам("Первое. Второе предложение", 9)).toBe("Первое…");
  });

  it("слово длиннее предела режет по символу — иначе вернули бы пустоту", () => {
    expect(обрезатьПоСловам("Сверхдлинноесловобезпробелов", 10)).toBe("Сверхдлин…");
  });

  it("пробелы по краям срезает", () => {
    expect(обрезатьПоСловам("   Текст   ", 100)).toBe("Текст");
  });

  it("пустое и вырожденные пределы не роняют", () => {
    expect(обрезатьПоСловам("", 50)).toBe("");
    expect(обрезатьПоСловам("Текст", 0)).toBe("");
    expect(обрезатьПоСловам("Текст", -5)).toBe("");
  });

  it("ровно на пределе не обрезает", () => {
    const t = "Ровно двадцать зн";
    expect(обрезатьПоСловам(t, t.length)).toBe(t);
  });
});
