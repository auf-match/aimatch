/**
 * Текущая дата для промптов.
 *
 * Зачем: модель живёт своей границей знаний и без подсказки считает недавнее
 * прошлое будущим. На живом прогоне это уже стоило кандидату red flag —
 * «кейс опубликован будущей датой (7 августа 2025)», хотя на дворе был
 * август 2026. Дальше модель ставила под сомнение достоверность его метрик,
 * а рекрутер видел бы предупреждение о подлоге на пустом месте.
 *
 * Второе, что чинится здесь же: пороги «несвежести» были вписаны в промпты
 * числами — «UI 2018-2020 года», «стиль 2010-2018». Такой порог устаревает
 * молча: год идёт, а планка стоит на месте, и работы пятилетней давности
 * продолжают считаться свежими.
 */

const MONTHS = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/** «24 августа 2026 года» */
export function formatRuDate(date: Date): string {
  return `${date.getDate()} ${MONTHS[date.getMonth()]} ${date.getFullYear()} года`;
}

/**
 * Блок для начала промпта: сегодняшняя дата и прямой запрет считать
 * прошедшее будущим.
 */
export function todayBlock(date: Date = new Date()): string {
  return `СЕГОДНЯ: ${formatRuDate(date)}. Твои внутренние представления о текущей дате могут отставать — ориентируйся только на эту. Дата НЕ является будущей, если она не позже сегодняшней: не помечай такие публикации как подозрительные.`;
}

/**
 * Граница несвежести: работы старше этого года считаем устаревшими.
 * Пять лет — столько живёт визуальный тренд в интерфейсах.
 */
export function staleBefore(date: Date = new Date(), years = 5): number {
  return date.getFullYear() - years;
}
