/**
 * Отдельный домен для публичной страницы: razbor.pragmatica.design.
 *
 * Приложение одно, сервер один, база одна — разделение только по имени
 * хоста. На публичном домене продукт недоступен вовсе: не «закрыт
 * паролем», а не существует. Иначе по адресу, который мы раздаём
 * дизайнерам, находился бы вход во внутренний инструмент агентства —
 * пусть и запароленный, но видимый.
 *
 * Имя домена вынесено в переменную окружения: поддомен могут сменить, а
 * пересобирать ради этого приложение не хочется.
 */

/** Что отвечать на запрос, пришедший на публичный домен. */
export type РешениеПоХосту =
  /** Отдать публичную страницу (адрес переписывается на /p/portfolio) */
  | { вид: "страница" }
  /** Пропустить как есть: приём заявок, статика, служебное */
  | { вид: "пропустить" }
  /** Ничего такого здесь нет */
  | { вид: "нет" };

const ХОСТ_ПО_УМОЛЧАНИЮ = "razbor.pragmatica.design";

/** Пути, которые на публичном домене работают как есть. */
const ПРОПУСКАТЬ = [
  "/api/public/", // приём заявок и опрос результата
  "/_next/", // сборка: без неё страница будет голой
  "/favicon", // иконка вкладки
];

/** Голое имя без порта: заголовок host приходит как «домен:3000». */
export function hostname(host: string | null | undefined): string {
  if (!host) return "";
  return host.trim().toLowerCase().split(":")[0];
}

/**
 * Пришёл ли запрос на публичный домен.
 *
 * Сравнение точное, без «заканчивается на». Проверка вида
 * endsWith("razbor.pragmatica.design") пропустила бы
 * «злой-razbor.pragmatica.design», а на публичном домене нет пароля —
 * цена ошибки здесь выше обычного.
 */
export function isPublicHost(host: string | null | undefined, ожидаемый?: string): boolean {
  const имя = hostname(host);
  if (!имя) return false;
  const цель = (ожидаемый || process.env.PUBLIC_HOST || ХОСТ_ПО_УМОЛЧАНИЮ).toLowerCase();
  return имя === цель;
}

/** Что делать с путём, пришедшим на публичный домен. */
export function решитьПоПути(pathname: string): РешениеПоХосту {
  const путь = pathname || "/";

  // Корень домена — сама страница. Её собственный адрес /p/portfolio тоже
  // оставляем рабочим: ссылки на него уже могли разойтись
  if (путь === "/" || путь === "/p/portfolio" || путь === "/p/portfolio/") {
    return { вид: "страница" };
  }

  if (ПРОПУСКАТЬ.some((p) => путь.startsWith(p))) return { вид: "пропустить" };

  // Всё остальное — внутренний продукт. На этом домене его нет
  return { вид: "нет" };
}
