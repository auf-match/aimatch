import { describe, it, expect } from "vitest";
import { прочитатьРазбор, запомнитьРазбор, забытьРазбор, КЛЮЧ } from "./saved-analysis";

/** Хранилище-заглушка: то же поведение, что у localStorage */
function хранилище(начальное: Record<string, string> = {}) {
  const данные = { ...начальное };
  return {
    данные,
    getItem: (k: string) => (k in данные ? данные[k] : null),
    setItem: (k: string, v: string) => void (данные[k] = v),
    removeItem: (k: string) => void delete данные[k],
  };
}

/** Похож на cuid: то, что выдаёт база */
const ID = "cmtrd4yxx0000pubeovk7b96s";

describe("запомнитьРазбор", () => {
  it("сохраняет заявку с отметкой времени", () => {
    const х = хранилище();
    запомнитьРазбор(х, ID);
    const о = JSON.parse(х.данные[КЛЮЧ]);
    expect(о.id).toBe(ID);
    expect(Number.isNaN(Date.parse(о.когда))).toBe(false);
  });

  it("не сохраняет непохожее на заявку", () => {
    const х = хранилище();
    запомнитьРазбор(х, "");
    запомнитьРазбор(х, "коротко");
    запомнитьРазбор(х, "../../../etc/passwd");
    expect(х.данные[КЛЮЧ]).toBeUndefined();
  });

  it("переживает недоступное хранилище", () => {
    const сломанное = {
      getItem: () => null,
      setItem: () => {
        throw new Error("QuotaExceeded");
      },
      removeItem: () => {},
    };
    // В инкогнито и при запрете на сайт хранилище бросает — страница
    // из-за этого падать не должна
    expect(() => запомнитьРазбор(сломанное, ID)).not.toThrow();
    expect(() => прочитатьРазбор(сломанное)).not.toThrow();
  });

  it("без хранилища ничего не делает", () => {
    expect(() => запомнитьРазбор(null, ID)).not.toThrow();
    expect(прочитатьРазбор(undefined)).toBeNull();
  });
});

describe("прочитатьРазбор", () => {
  it("возвращает сохранённое", () => {
    const х = хранилище();
    запомнитьРазбор(х, ID);
    expect(прочитатьРазбор(х)?.id).toBe(ID);
  });

  it("на пустом хранилище отвечает ничем", () => {
    expect(прочитатьРазбор(хранилище())).toBeNull();
  });

  it("мусор в хранилище не роняет чтение", () => {
    expect(прочитатьРазбор(хранилище({ [КЛЮЧ]: "не json" }))).toBeNull();
    expect(прочитатьРазбор(хранилище({ [КЛЮЧ]: "[1,2,3]" }))).toBeNull();
    expect(прочитатьРазбор(хранилище({ [КЛЮЧ]: '{"id":42}' }))).toBeNull();
  });

  it("подложенный чужой путь не принимает за заявку", () => {
    // Из хранилища значение попадёт прямо в адрес ссылки
    expect(прочитатьРазбор(хранилище({ [КЛЮЧ]: '{"id":"../admin"}' }))).toBeNull();
    expect(
      прочитатьРазбор(хранилище({ [КЛЮЧ]: '{"id":"https://evil.ru"}' })),
    ).toBeNull();
  });

  it("запись без даты читает, дата не обязательна", () => {
    const о = прочитатьРазбор(хранилище({ [КЛЮЧ]: `{"id":"${ID}"}` }));
    expect(о?.id).toBe(ID);
    expect(о?.когда).toBe("");
  });
});

describe("забытьРазбор", () => {
  it("стирает запись", () => {
    const х = хранилище();
    запомнитьРазбор(х, ID);
    забытьРазбор(х);
    expect(прочитатьРазбор(х)).toBeNull();
  });
});
