import { describe, it, expect } from "vitest";
import { applyRendition } from "./public-rendition";
import type { PublicResult } from "./public-result";

const исходный: PublicResult = {
  общее: "Портфолио сильного дизайнера.",
  критерии: [
    { название: "Визуал", ступень: "сильный", пояснение: "Композиция уверенная." },
    { название: "UX", ступень: "средний", пояснение: "Флоу читаются." },
  ],
  работает: ["Отбор работ сделан"],
  нехватает: ["Роль не указана"],
  кейсы: [{ название: "Банк", описание: "Показан путь." }],
};

const годное = {
  общее: "У тебя сильное портфолио.",
  пояснения: ["Ты уверенно строишь композицию.", "Твои флоу читаются."],
  работает: ["Ты отобрал работы"],
  нехватает: ["Ты не указал свою роль"],
  кейсы: ["Ты показал путь."],
};

describe("applyRendition", () => {
  it("подменяет тексты, оставляя названия и ступени", () => {
    const r = applyRendition(исходный, годное)!;
    expect(r.общее).toBe("У тебя сильное портфолио.");
    expect(r.критерии[0]).toEqual({
      название: "Визуал",
      ступень: "сильный",
      пояснение: "Ты уверенно строишь композицию.",
    });
    expect(r.кейсы[0].название).toBe("Банк");
    expect(r.кейсы[0].описание).toBe("Ты показал путь.");
  });

  it("отвергает переложение, где пунктов меньше", () => {
    // Иначе пояснение про UX уехало бы к «Визуалу», и человек прочитал бы
    // про себя чужое
    expect(applyRendition(исходный, { ...годное, пояснения: ["Только одно."] })).toBeNull();
  });

  it("отвергает и когда пунктов больше", () => {
    expect(
      applyRendition(исходный, { ...годное, работает: ["Раз", "Два"] }),
    ).toBeNull();
  });

  it("отвергает пустые строки — это потеря смысла, а не редактура", () => {
    expect(applyRendition(исходный, { ...годное, общее: "  " })).toBeNull();
    expect(applyRendition(исходный, { ...годное, пояснения: ["Есть", " "] })).toBeNull();
  });

  it("пустое описание кейса допускает: оно бывает пустым и в исходнике", () => {
    const r = applyRendition(исходный, { ...годное, кейсы: [""] });
    expect(r).not.toBeNull();
    expect(r!.кейсы[0].описание).toBe("");
  });

  it("не строки в списках отвергает", () => {
    expect(applyRendition(исходный, { ...годное, работает: [42] })).toBeNull();
    expect(applyRendition(исходный, { ...годное, нехватает: "не массив" })).toBeNull();
  });

  it("на отсутствующем переложении возвращает null", () => {
    expect(applyRendition(исходный, null)).toBeNull();
    expect(applyRendition(исходный, undefined)).toBeNull();
    expect(applyRendition(исходный, {})).toBeNull();
  });

  it("не даёт модели переписать наше «оценить не вышло»", () => {
    const безОценки: PublicResult = {
      ...исходный,
      критерии: [
        { название: "Визуал", ступень: null, пояснение: "Оценить не вышло: работ не нашлось." },
        исходный.критерии[1],
      ],
    };
    const r = applyRendition(безОценки, {
      ...годное,
      пояснения: ["Твой визуал сильный и уверенный.", "Твои флоу читаются."],
    })!;
    // Признание осталось нашим: модель легко превратила бы его в оценку,
    // которой не было
    expect(r.критерии[0].пояснение).toBe("Оценить не вышло: работ не нашлось.");
    expect(r.критерии[1].пояснение).toBe("Твои флоу читаются.");
  });

  it("исходный результат не портит", () => {
    const копия = JSON.parse(JSON.stringify(исходный));
    applyRendition(исходный, годное);
    expect(исходный).toEqual(копия);
  });

  it("пустые списки на входе не мешают", () => {
    const пустой: PublicResult = { ...исходный, работает: [], нехватает: [], кейсы: [] };
    const r = applyRendition(пустой, { ...годное, работает: [], нехватает: [], кейсы: [] });
    expect(r).not.toBeNull();
    expect(r!.работает).toEqual([]);
  });
});
