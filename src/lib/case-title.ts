/**
 * Как назвать кейс в подписи к кадрам.
 *
 * Раньше брали заголовок вкладки. На конструкторах вроде Framer он один
 * на весь сайт, и все кейсы приезжали к модели под именем автора —
 * «Lukin Slava», четыре штуки подряд. Модель не могла их различить, а в
 * разделе «По кейсам» человек видел четыре одинаковых названия.
 *
 * Порядок источников — от самого точного к самому грубому:
 *   1. h1 страницы кейса: его пишет автор про эту работу;
 *   2. текст ссылки с главной: тоже авторский, но бывает слипшимся;
 *   3. заголовок вкладки — если он хоть чем-то отличается от общего.
 */

/** Хвосты площадок: «Название :: Behance», «Название | Dribbble». */
const ХВОСТ_ПЛОЩАДКИ = /\s*(::|[|–—-])\s*(Behance|Dribbble|Notion|Figma).*$/i;

const МАКС = 80;

export interface ИсточникиЗаголовка {
  /** Заголовок первого уровня на странице кейса */
  h1?: string | null;
  /** Заголовок вкладки страницы кейса */
  title?: string | null;
  /** Текст ссылки, по которой мы на кейс пришли */
  linkText?: string | null;
  /** Заголовок вкладки главной страницы — с ним сравниваем на «то же самое» */
  siteTitle?: string | null;
}

const чисто = (v: unknown): string =>
  typeof v === "string" ? v.replace(ХВОСТ_ПЛОЩАДКИ, "").replace(/\s+/g, " ").trim() : "";

/** Совпадает ли с названием сайта — тогда это не имя кейса. */
function этоИмяСайта(кандидат: string, сайт: string): boolean {
  if (!сайт) return false;
  return кандидат.toLowerCase() === сайт.toLowerCase();
}

export function выбратьЗаголовокКейса(и: ИсточникиЗаголовка): string {
  const сайт = чисто(и.siteTitle);

  for (const кандидат of [чисто(и.h1), чисто(и.linkText), чисто(и.title)]) {
    // Слишком короткое — это стрелка или номер, а не название
    if (кандидат.length < 3) continue;
    if (этоИмяСайта(кандидат, сайт)) continue;
    return кандидат.slice(0, МАКС);
  }

  // Ничего не подошло: пусть лучше подписи не будет, чем имя автора
  // четырежды подряд — по нему кейсы всё равно не различить
  return "";
}
