/**
 * Память браузера о своём разборе.
 *
 * Экран ожидания обещает: «страницу можно закрыть, ты сможешь вернуться к
 * результату». Само по себе это неправдой и было — ссылку человек должен
 * был скопировать руками, а закрыв вкладку без этого, терял результат
 * навсегда: адреса он не знает, а прислать его мы не умеем.
 *
 * Здесь ссылка запоминается в самом браузере, и на форме появляется путь
 * назад. Обещание становится правдой — в пределах этого браузера. Другое
 * устройство и режим инкогнито по-прежнему не покрыты: для этого нужен
 * бот в телеграме, о котором говорили отдельно.
 *
 * Работа идёт через переданное хранилище, а не через глобальный
 * localStorage: так логика проверяется тестами без браузера, а вызывающий
 * сам решает, что подставить.
 */

export const КЛЮЧ = "прожарочная:разбор";

export interface СохранённыйРазбор {
  id: string;
  /** Когда отправили заявку — по нему решаем, что показывать первым */
  когда: string;
}

/** Похоже ли на идентификатор заявки. Cuid — буквы и цифры, без разделителей. */
function похожеНаId(v: unknown): v is string {
  return typeof v === "string" && /^[a-z0-9]{20,40}$/i.test(v);
}

/**
 * Хранилище может быть недоступно: режим инкогнито, запрет на сайт,
 * переполнение. Любая работа с ним обёрнута — отсутствие памяти не повод
 * ронять страницу.
 */
type Хранилище = Pick<Storage, "getItem" | "setItem" | "removeItem">;

export function прочитатьРазбор(х: Хранилище | null | undefined): СохранённыйРазбор | null {
  if (!х) return null;
  let сырое: string | null;
  try {
    сырое = х.getItem(КЛЮЧ);
  } catch {
    return null;
  }
  if (!сырое) return null;

  try {
    const о = JSON.parse(сырое) as Partial<СохранённыйРазбор>;
    if (!похожеНаId(о?.id)) return null;
    return {
      id: о.id,
      когда: typeof о.когда === "string" ? о.когда : "",
    };
  } catch {
    // Мусор в хранилище — ведём себя так, будто памяти нет
    return null;
  }
}

export function запомнитьРазбор(х: Хранилище | null | undefined, id: string): void {
  if (!х || !похожеНаId(id)) return;
  try {
    х.setItem(КЛЮЧ, JSON.stringify({ id, когда: new Date().toISOString() }));
  } catch {
    // Переполнено или запрещено — молча живём без памяти
  }
}

export function забытьРазбор(х: Хранилище | null | undefined): void {
  if (!х) return;
  try {
    х.removeItem(КЛЮЧ);
  } catch {
    // Нечего ловить: удаление и так делалось на всякий случай
  }
}
