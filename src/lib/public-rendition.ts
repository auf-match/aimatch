import type { PublicResult } from "./public-result";

/**
 * Приложение переложенного текста к разбору.
 *
 * Вынесено из сервиса, потому что здесь легко ошибиться молча: модель
 * вернёт список короче исходного, и часть пунктов подменится соседними —
 * человек прочитает про себя чужое. Поэтому длины сверяются, и при
 * несовпадении переложение отвергается целиком.
 *
 * Отвергнуть безопаснее, чем склеить наполовину: исходный текст верный,
 * просто написан в третьем лице.
 */

export interface Переложение {
  общее?: unknown;
  пояснения?: unknown;
  работает?: unknown;
  нехватает?: unknown;
  кейсы?: unknown;
}

const строки = (v: unknown): string[] | null =>
  Array.isArray(v) && v.every((x) => typeof x === "string") ? (v as string[]) : null;

/**
 * Накладывает переложение на результат. Возвращает null, если оно не
 * годится — тогда показываем исходный текст, он верный.
 */
export function applyRendition(
  исходный: PublicResult,
  переложение: Переложение | null | undefined,
): PublicResult | null {
  if (!переложение || typeof переложение !== "object") return null;

  const общее = typeof переложение.общее === "string" ? переложение.общее.trim() : "";
  const пояснения = строки(переложение.пояснения);
  const работает = строки(переложение.работает);
  const нехватает = строки(переложение.нехватает);
  const кейсы = строки(переложение.кейсы);

  if (пояснения === null || работает === null || нехватает === null || кейсы === null) {
    return null;
  }

  // Длины обязаны совпадать: иначе пояснение уедет к чужому критерию
  if (
    пояснения.length !== исходный.критерии.length ||
    работает.length !== исходный.работает.length ||
    нехватает.length !== исходный.нехватает.length ||
    кейсы.length !== исходный.кейсы.length
  ) {
    return null;
  }

  // Пустая строка в переложении — потеря смысла, а не редактура
  if (
    !общее ||
    [...пояснения, ...работает, ...нехватает].some((s) => !s.trim())
  ) {
    return null;
  }

  return {
    общее,
    /*
     * У критерия без ступени пояснение наше собственное — «оценить не
     * вышло». Модель его не переписывает: она видит только текст и легко
     * превратит признание в оценку, которой не было.
     */
    критерии: исходный.критерии.map((k, i) =>
      k.ступень === null ? k : { ...k, пояснение: пояснения[i].trim() },
    ),
    работает: работает.map((s) => s.trim()),
    нехватает: нехватает.map((s) => s.trim()),
    // У кейса описание может быть пустым и в исходнике — это не потеря
    кейсы: исходный.кейсы.map((c, i) => ({ ...c, описание: кейсы[i].trim() })),
  };
}
