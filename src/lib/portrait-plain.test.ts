import { describe, it, expect } from "vitest";
import { toPlainText } from "./portrait-plain";

describe("toPlainText", () => {
  it("заголовок раздела становится жирным", () => {
    expect(toPlainText("## Кого ищем одной фразой")).toBe(
      "**Кого ищем одной фразой**",
    );
  });

  // Модель порой оборачивает заголовок сама — иначе вышло бы ****Обязательно****
  it("не задваивает звёздочки, если модель уже их поставила", () => {
    expect(toPlainText("## **Обязательно**")).toBe("**Обязательно**");
  });

  it("подзаголовок остаётся в обычном регистре, но с двоеточием", () => {
    expect(toPlainText("### Частое возражение")).toBe("Частое возражение:");
  });

  it("не задваивает двоеточие, если оно уже есть", () => {
    expect(toPlainText("### Частое возражение:")).toBe("Частое возражение:");
  });

  it("перед заголовком встаёт пустая строка", () => {
    expect(toPlainText("Текст\n## Раздел\nЕщё")).toBe(
      "Текст\n\n**Раздел**\nЕщё",
    );
  });

  it("маркеры списка становятся тире", () => {
    expect(toPlainText("- один\n* два\n+ три")).toBe("— один\n— два\n— три");
  });

  it("нумерованный список сохраняет номера", () => {
    expect(toPlainText("1. первый\n2. второй")).toBe("1. первый\n2. второй");
  });

  it("вложенный пункт остаётся вложенным", () => {
    expect(toPlainText("- верх\n  - низ")).toBe("— верх\n  — низ");
  });

  // Telegram разбирает ** и __ при вставке — это и есть форматирование
  it("сохраняет то, что Telegram покажет начертанием", () => {
    expect(toPlainText("**важно** и __курсивом__ и `моно`")).toBe(
      "**важно** и __курсивом__ и `моно`",
    );
  });

  // А одиночные Telegram показал бы буквально
  it("снимает одиночные звёздочки и подчёркивания", () => {
    expect(toPlainText("*мягко* и _этак_")).toBe("мягко и этак");
  });

  // Иначе «оплата 5 * 3 часа» превратилась бы в кашу
  it("не трогает звёздочку и подчёркивание внутри текста", () => {
    expect(toPlainText("5 * 3 = 15")).toBe("5 * 3 = 15");
    expect(toPlainText("файл_имя_такое")).toBe("файл_имя_такое");
  });

  it("ссылку разворачивает в текст с адресом", () => {
    expect(toPlainText("[портфолио](https://ex.com)")).toBe(
      "портфолио (https://ex.com)",
    );
  });

  it("обратные кавычки оставляет — Telegram делает моноширинный", () => {
    expect(toPlainText("поле `title`")).toBe("поле `title`");
  });

  it("выбрасывает горизонтальную черту", () => {
    expect(toPlainText("до\n---\nпосле")).toBe("до\nпосле");
  });

  // Промпт запрещает обёртку, но модель иногда добавляет её всё равно
  it("выбрасывает обёртку из тройных кавычек", () => {
    expect(toPlainText("```\nтекст\n```")).toBe("текст");
  });

  it("снимает маркер цитаты", () => {
    expect(toPlainText("> цитата")).toBe("цитата");
  });

  it("схлопывает лишние пустые строки", () => {
    expect(toPlainText("а\n\n\n\nб")).toBe("а\n\nб");
  });

  it("решётки в тексте не остаётся нигде", () => {
    const md = [
      "## Условия",
      "- Грейд: **Senior**",
      "",
      "### Частое возражение",
      "Ответ.",
      "",
      "## Стоп-факторы",
      "- Не приносить *моушен*",
    ].join("\n");
    const out = toPlainText(md);
    expect(out).not.toMatch(/#/);
    expect(out).toContain("**Условия**");
    expect(out).toContain("Частое возражение:");
    expect(out).toContain("— Грейд: **Senior**");
    // Звёздочки только парные: непарная показалась бы в сообщении
    expect((out.match(/\*\*/g) ?? []).length % 2).toBe(0);
  });

  it("пустой ввод не ломает", () => {
    expect(toPlainText("")).toBe("");
    expect(toPlainText("\n\n")).toBe("");
  });
});
