/**
 * Обрезка текста по границе слова.
 *
 * Нужна карточкам критериев: их высота задана, а длину пояснения пишет
 * модель, и однажды она напишет вдвое больше обычного. Тогда текст
 * вылезает за карточку — это уже случалось на проверках.
 *
 * Обрезаем по слову, а не по символу: обрывок вида «типографи…» читается
 * как ошибка, а «…на уверенном…» — как сокращение.
 */

/** Многоточие как один знак — так оно и набирается */
const МНОГОТОЧИЕ = "…";

export function обрезатьПоСловам(текст: string, предел: number): string {
  const t = (текст ?? "").trim();
  if (предел <= 0) return "";
  if (t.length <= предел) return t;

  // Место под многоточие берём из предела, иначе выйдем за него
  const край = предел - МНОГОТОЧИЕ.length;
  const кусок = t.slice(0, край);

  const пробел = кусок.lastIndexOf(" ");
  // Слово длиннее предела — режем по символу, иначе вернём пустоту
  const основа = пробел > 0 ? кусок.slice(0, пробел) : кусок;

  // Знаки препинания перед многоточием выглядят как опечатка
  return основа.replace(/[\s.,;:—–-]+$/u, "") + МНОГОТОЧИЕ;
}
