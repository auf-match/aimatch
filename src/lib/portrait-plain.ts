/**
 * Markdown от модели → текст, готовый к вставке в Telegram.
 *
 * Промпт задаёт структуру заголовками `## `, и это правильно: так модель
 * держит порядок разделов. Но Telegram понимает не весь markdown — часть
 * синтаксиса он разбирает при вставке, а остальное показывает буквально,
 * и текст приходится править руками перед отправкой.
 *
 * Поэтому делим разметку на две части: что Telegram рисует — оставляем,
 * что показывает как есть — снимаем.
 *
 *   ОСТАЁТСЯ           **жирный**, __курсив__, `моноширинный`
 *   СНИМАЕТСЯ          ## решётки, *одиночные звёздочки*, _подчёркивания_,
 *                      [ссылки](адрес), ```обёртки```, горизонтальные черты
 *
 * Заголовки переводятся в жирный, а не в заглавные: Telegram показывает
 * его настоящим начертанием, и это читается лучше капители.
 *
 *   ## Обязательно     → **Обязательно**
 *   ### Возражение     → Возражение:      (второй уровень — двоеточием,
 *                                          иначе оба уровня одинаковые)
 *   - пункт            → — пункт          (тире, как в карточке вакансии)
 *
 * Жирный через юникод-символы (𝗮𝗯𝗰) не делаем: он ломает поиск по
 * сообщению и не читается программами экранного доступа.
 */

/** Символы списка, которые встречаются в ответах модели. */
const BULLET = /^(\s*)[-*+]\s+/;
/** Нумерованный пункт оставляем как есть — номер несёт смысл. */
const NUMBERED = /^\s*\d+[.)]\s+/;

/**
 * Снимает разметку, которую Telegram не разбирает. Парный `**`, `__` и
 * обратные кавычки не трогаем — их он покажет начертанием.
 */
function stripInline(s: string): string {
  // Парную разметку прячем за метки, иначе правило для одиночных её съест:
  // в «**Senior**» оно видит звёздочку, «*Senior*» и звёздочку, и снимает
  // одну пару. Отличить это лукахедами не выходит — проще убрать с дороги.
  //
  // Метка на управляющих символах, а не из цифр: голая цифра совпала бы с
  // настоящим числом в тексте и подменила бы его.
  const kept: string[] = [];
  const hide = (m: string) => `\u0000${kept.push(m) - 1}\u0000`;

  return (
    s
      .replace(/\*\*[^*]+\*\*/g, hide)
      .replace(/__[^_]+__/g, hide)
      .replace(/`[^`]+`/g, hide)
      // Одиночные *курсив* и _курсив_ Telegram показал бы буквально.
      // Границу считаем по \p{L}, а не по \w: \w в JS не знает кириллицы,
      // и «файл_имя_такое» превращалось в «файлимятакое».
      .replace(/(?<![\p{L}\p{N}*])\*(?!\s)(.+?)(?<!\s)\*(?![\p{L}\p{N}*])/gu, "$1")
      .replace(/(?<![\p{L}\p{N}_])_(?!\s)(.+?)(?<!\s)_(?![\p{L}\p{N}_])/gu, "$1")
      // [текст](ссылка) → текст (ссылка): такую ссылку Telegram не соберёт,
      // а голый адрес он делает кликабельным сам
      .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1 ($2)")
      .replace(/\u0000(\d+)\u0000/g, (_, i) => kept[Number(i)])
      .trimEnd()
  );
}

export function toPlainText(markdown: string): string {
  const out: string[] = [];

  for (const raw of markdown.replace(/\r\n/g, "\n").split("\n")) {
    const line = raw.trimEnd();

    // Горизонтальная черта: в тексте без разметки это мусор
    // Три и больше символов подряд: ---, ***, ___, а также «- - -»
    if (/^\s*(?:[-*_]\s*){3,}$/.test(line)) continue;

    // Обёртка ```…``` — промпт её запрещает, но модель иногда добавляет
    if (/^\s*```/.test(line)) continue;

    const heading = line.match(/^(#{1,6})\s+(.*)$/);
    if (heading) {
      const [, hashes, textRaw] = heading;
      // Модель иногда уже оборачивает заголовок в **…** — снимаем, чтобы
      // не получить ****Обязательно****
      const text = stripInline(textRaw)
        .replace(/^\*\*(.*)\*\*$/, "$1")
        .replace(/[:\s]+$/, "");
      if (!text) continue;
      if (out.length && out[out.length - 1] !== "") out.push("");
      out.push(hashes.length <= 2 ? `**${text}**` : `${text}:`);
      continue;
    }

    if (NUMBERED.test(line)) {
      out.push(stripInline(line.trimStart()));
      continue;
    }

    const bullet = line.match(BULLET);
    if (bullet) {
      // Вложенность сохраняем отступом, маркер везде один
      const indent = bullet[1].length >= 2 ? "  " : "";
      out.push(`${indent}— ${stripInline(line.replace(BULLET, ""))}`);
      continue;
    }

    // Цитата `> …` — в плоском тексте маркер не нужен
    out.push(stripInline(line.replace(/^\s*>\s?/, "")));
  }

  return out
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
