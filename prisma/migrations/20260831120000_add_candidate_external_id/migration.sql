-- Идентификатор человека в системе-источнике: номер в Хантфлоу, id профиля
-- у поисковика. Нужен, чтобы регулярная выгрузка узнавала уже заведённого
-- человека, даже если ссылка на портфолио другая или её нет вовсе.
ALTER TABLE "Candidate" ADD COLUMN "externalId" TEXT;

-- Пара «источник + идентификатор» уникальна: одинаковые номера у разных
-- источников не конфликтуют. Пустые значения Postgres считает различными,
-- поэтому все существующие записи (у них externalId пуст) не задеты.
CREATE UNIQUE INDEX "Candidate_source_externalId_key" ON "Candidate"("source", "externalId");
